#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPT="$ROOT/ios/scripts/prepare-title-lift.sh"
bash -n "$SCRIPT"
HELP="$(bash "$SCRIPT" --help)"
grep -Fq 'DECRYPTED_EBOOT.ELF' <<<"$HELP"
grep -Fq 'PS3RECOMP_DIR' <<<"$HELP"
PATCHER="$ROOT/ios/scripts/patch-ps3recomp-ios-metal.py"
grep -Fq 'tools/ppu_lifter.py' "$PATCHER"
grep -Fq '0xF8410028' "$PATCHER"
grep -Fq 'vm_write64(ctx->gpr[1] + 0x28, ctx->gpr[2])' "$PATCHER"
grep -Fq 'PPU_ICACHE_N = 1024' "$PATCHER"
grep -Fq 'g_ppu_icache[PPU_ICACHE_N]' "$PATCHER"
grep -Fq 'macos_ppu_runtime' "$PATCHER"
grep -Fq 'g_ppu_image_ranges' "$PATCHER"
grep -Fq 'ps3_ppu_dispatch_depth_slot' "$PATCHER"
grep -Fq 'ps3_ppu_vcall_sp_slot' "$PATCHER"
grep -Fq 'patch_macos_disc_vfs(root)' "$PATCHER"
grep -Fq 'soulbrandt_disc_vfs_list' "$PATCHER"
grep -Fq 'main_stack_info(uint32_t* addr, uint32_t* size)' "$PATCHER"
grep -Fq 'entry argument stack overlaps loaded image' "$PATCHER"
grep -Fq 'ctx.gpr[5] = argv_base + (argc_n + 1u) * 8u;' "$PATCHER"
grep -Fq -- '--code-end 0x16bb5e4 --chunks 128' "$SCRIPT"
grep -Fq 'apply_macos_ppu_setjmp.py' "$SCRIPT"
test -s "$ROOT/ios/scripts/apply_macos_ppu_setjmp.py"
test -s "$ROOT/ios/SoulbrandtIOS/DSGuestSetjmp.cpp"
grep -Fq 'DSGuestSetjmp.cpp' "$ROOT/ios/scripts/build-ppu-lift-ios.sh"
echo "iOS title-lift pipeline preflight smoke test passed"
